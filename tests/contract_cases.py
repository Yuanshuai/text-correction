def _build_contract_cases() -> list[dict]:
    cases: list[dict] = []
    cid = 101

    for name, content in _PLACEHOLDER_CASES:
        cases.append(_c(cid, f"合同-填空位-{name}", content, "no_error", ["placeholder"]))
        cid += 1

    for name, content in _CLEAN_CASES:
        cases.append(_c(cid, f"合同-无错-{name}", content, "no_error", ["clean"]))
        cid += 1

    for name, content, min_err in _TYPO_SINGLE:
        cases.append(_c(cid, f"合同-单错-{name}", content, "has_error", ["typo"], min_errors=min_err))
        cid += 1

    for name, content, min_err in _TYPO_SINGLE_EXTRA:
        cases.append(_c(cid, f"合同-单错-{name}", content, "has_error", ["typo"], min_errors=min_err))
        cid += 1

    for name, content, min_err in _TYPO_MULTI:
        # min_err 为 0 表示该句并未埋错别字，按"无错句"判定，用于检查误报
        expect = "has_error" if min_err else "no_error"
        label = "合同-多错" if min_err else "合同-无误报"
        cases.append(_c(cid, f"{label}-{name}", content, expect, ["multi-error"], min_errors=min_err))
        cid += 1

    for name, content in _STRUCTURE_CASES:
        cases.append(_c(cid, f"合同-专业-{name}", content, "structure", ["terminology"]))
        cid += 1

    for name, content, expect, min_err in _COMBO_CASES:
        extra = {"min_errors": min_err} if min_err else {}
        cases.append(_c(cid, f"合同-组合-{name}", content, expect, ["combo"], **extra))
        cid += 1

    assert len(cases) == 100, f"合同用例数量应为 100，当前为 {len(cases)}"
    return cases


CONTRACT_CASES: list[dict] = _build_contract_cases()
